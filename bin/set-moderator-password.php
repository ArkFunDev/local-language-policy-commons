<?php
/**
 * Create or update the moderator password.
 *
 *   php bin/set-moderator-password.php               (prompts for the password)
 *   php bin/set-moderator-password.php --print-hash  (prints the hash only, e.g. for LLPC_MODERATOR_PASSWORD_HASH)
 *
 * Writes config/config.local.php, which is ignored by Git.
 */
if (PHP_SAPI !== 'cli') {
    exit(1);
}

$root  = dirname(__DIR__);
$args  = array_slice($argv, 1);
$print = in_array('--print-hash', $args, true);

echo "Choose a moderator password (at least 12 characters): ";
$canHide = (DIRECTORY_SEPARATOR === '/' && function_exists('shell_exec'));
if ($canHide) {
    @shell_exec('stty -echo 2>/dev/null');
}
$password = rtrim((string) fgets(STDIN), "\r\n");
if ($canHide) {
    @shell_exec('stty echo 2>/dev/null');
}
echo "\n";

$weak = ['123456', '12345678', 'password', 'admin', 'moderator', 'changeme', 'qwerty', 'letmein'];
if (strlen($password) < 12) {
    fwrite(STDERR, "Error: the password must be at least 12 characters.\n");
    exit(1);
}
if (in_array(strtolower($password), $weak, true)) {
    fwrite(STDERR, "Error: that password is too common.\n");
    exit(1);
}

$hash = password_hash($password, PASSWORD_DEFAULT);

if ($print) {
    echo $hash . "\n";
    exit(0);
}

$file = $root . '/config/config.local.php';
$cfg  = is_file($file) ? require $file : [];
if (!is_array($cfg)) {
    $cfg = [];
}
$cfg['moderator_password_hash'] = $hash;

$php = "<?php\n// Generated by bin/set-moderator-password.php. Do not commit this file.\nreturn "
    . var_export($cfg, true) . ";\n";

if (file_put_contents($file, $php, LOCK_EX) === false) {
    fwrite(STDERR, "Error: could not write $file\n");
    exit(1);
}
@chmod($file, 0640);
echo "Saved to config/config.local.php. You can now log in at /login.php\n";
